/** Fjord Fiesta palette (ART.md targets, sRGB → linear-ish 0…1 floats). */
import type { RGB } from './geometry';

export function hex(value: string): RGB {
  const clean = value.replace('#', '');
  const number = Number.parseInt(clean, 16);
  return [((number >> 16) & 0xff) / 255, ((number >> 8) & 0xff) / 255, (number & 0xff) / 255];
}


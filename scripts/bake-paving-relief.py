"""Bake shallow, seamless paving relief from the unchanged painted cobble tile.
Run: python3 scripts/bake-paving-relief.py (requires Pillow).
No texture is rewritten; only a 64x64 scalar height table enters the client.
"""
from pathlib import Path
from PIL import Image, ImageFilter, ImageStat
import base64
import hashlib

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'apps/client/public/art/tex/cobblestone_color.jpg'
TARGET = ROOT / 'apps/client/src/rendering/map/paving-height.ts'
SIZE = 64
rgb = Image.open(SOURCE).convert('RGB')
mean = [value / 255 for value in ImageStat.Stat(rgb).mean]
image = rgb.convert('L')
w, h = image.size
margin = 32
wrapped = Image.new('L', (w + margin * 2, h + margin * 2))
for dx in range(-1, 2):
    for dy in range(-1, 2):
        wrapped.paste(image, (margin + dx * w, margin + dy * h))
# The dark painted joints are recessed; broad stone faces rise smoothly.
mask = wrapped.point(lambda value: 255 if value > 42 else 0)
distances = [0] * (SIZE * SIZE)
for level in range(24):
    for row in range(SIZE):
        for col in range(SIZE):
            if mask.getpixel((margin + round(col * w / SIZE), margin + round(row * h / SIZE))):
                distances[row * SIZE + col] += 1
    mask = mask.filter(ImageFilter.MinFilter(3))
soft = wrapped.filter(ImageFilter.GaussianBlur(12))
heights = bytearray()
for row in range(SIZE):
    for col in range(SIZE):
        t = min(1, distances[row * SIZE + col] / 20)
        dome = t * t * (3 - 2 * t)
        paint = soft.getpixel((margin + round(col * w / SIZE), margin + round(row * h / SIZE))) / 255
        heights.append(round(255 * dome * (0.72 + paint * 0.28)))
encoded = base64.b64encode(heights).decode('ascii')
digest = hashlib.sha256(SOURCE.read_bytes()).hexdigest()
TARGET.write_text(f'''/** Generated by scripts/bake-paving-relief.py from the unchanged painted tile. */
export const PAVING_SOURCE_SHA256 = '{digest}';
export const PAVING_SOURCE_MEAN_RGB = {mean} as const;
export const PAVING_TILE_METERS = 2;
export const PAVING_HEIGHT_SIZE = {SIZE};
const encoded = '{encoded}';
const heights = Uint8Array.from(atob(encoded), c => c.charCodeAt(0));

/** Bilinear, wrapped height samples in exactly the same UV space as the paint. */
export function paintedPavingHeight(x: number, z: number): number {{
  const u = ((x / PAVING_TILE_METERS) % 1 + 1) % 1 * PAVING_HEIGHT_SIZE;
  const v = ((z / PAVING_TILE_METERS) % 1 + 1) % 1 * PAVING_HEIGHT_SIZE;
  const ix = Math.floor(u), iz = Math.floor(v);
  const sample = (a: number, b: number): number => heights[(b % PAVING_HEIGHT_SIZE) * PAVING_HEIGHT_SIZE + a % PAVING_HEIGHT_SIZE]! / 255;
  const a = sample(ix, iz) * (1 - (u - ix)) + sample(ix + 1, iz) * (u - ix);
  const b = sample(ix, iz + 1) * (1 - (u - ix)) + sample(ix + 1, iz + 1) * (u - ix);
  return a * (1 - (v - iz)) + b * (v - iz);
}}
''')
print(f'Baked {len(heights)} height samples; source texture unchanged.')
